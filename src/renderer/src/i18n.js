export function makeT(lang) {
  return (key, vars) => {
    const dict = I18N[lang] || I18N.fi
    let str = dict[key] ?? I18N.fi[key] ?? key
    if (vars) {
      for (const k in vars) str = str.replace(`{{${k}}}`, vars[k])
    }
    return str
  }
}
